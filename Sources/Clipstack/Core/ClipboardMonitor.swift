import AppKit
import CryptoKit

/// Watches the general pasteboard and records each new copy.
///
/// macOS has no notification for pasteboard changes, so like every clipboard
/// manager this polls `changeCount`, which is a cheap integer read.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let pasteboard = NSPasteboard.general
    private let settings = AppSettings.shared
    private var timer: Timer?
    private var lastChangeCount = 0

    /// Markers that apps put on the pasteboard to say "don't keep this"
    /// (see nspasteboard.org): passwords, one-time codes, generated content.
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    func start() {
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.1
        // .common keeps polling while a menu is open.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Called after Clipstack itself writes to the pasteboard, so pasting an item
    /// doesn't record it again.
    func skipCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard settings.isRecordingActive else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if settings.ignoreConcealed, !types.isDisjoint(with: Self.sensitiveTypes) { return }

        let source = NSWorkspace.shared.frontmostApplication
        if let bundleID = source?.bundleIdentifier, settings.excludedBundleIDs.contains(bundleID) { return }

        guard let clip = ClipExtractor.extract(from: pasteboard, types: types, source: source, settings: settings) else { return }
        ClipStore.shared.insert(clip)
    }
}

/// Turns the pasteboard contents into a `CapturedClip`.
enum ClipExtractor {
    private static let maxTextLength = 2_000_000
    private static let maxImageBytes = 25_000_000

    static func extract(
        from pasteboard: NSPasteboard, types: Set<String>, source: NSRunningApplication?, settings: AppSettings
    ) -> CapturedClip? {
        let sourceID = source?.bundleIdentifier
        let sourceName = source?.localizedName

        // Files first: copying in Finder also puts the file name and icon on the pasteboard.
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            guard settings.captureFiles else { return nil }
            let paths = urls.map(\.path)
            let joined = paths.joined(separator: "\n")
            return CapturedClip(
                kind: .file, text: joined, filePaths: paths,
                sourceBundleID: sourceID, sourceAppName: sourceName, contentHash: hash("file", joined)
            )
        }

        // Text wins over images: spreadsheets and office apps put both on the pasteboard.
        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf16.count <= maxTextLength else { return nil }
            var kind = textKind(for: string)
            var rtf: Data?
            if kind == .text, let data = pasteboard.data(forType: .rtf), data.count < 5_000_000 {
                kind = .richText
                rtf = data
            }
            return CapturedClip(
                kind: kind, text: string, rtfData: rtf,
                sourceBundleID: sourceID, sourceAppName: sourceName, contentHash: hash("text", string)
            )
        }

        if settings.captureImages, let image = readImage(from: pasteboard) {
            return CapturedClip(
                kind: .image, imageData: image.png, thumbnailData: image.thumbnail, imageSize: image.size,
                sourceBundleID: sourceID, sourceAppName: sourceName, contentHash: hash(data: image.png)
            )
        }

        return nil
    }

    static func textKind(for string: String) -> ClipKind {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        if HexColor.isHexColor(trimmed) { return .color }
        if isLink(trimmed) { return .link }
        return .text
    }

    static func isLink(_ string: String) -> Bool {
        guard string.count < 4000, !string.contains(where: \.isWhitespace),
              let url = URL(string: string), let scheme = url.scheme?.lowercased()
        else { return false }
        switch scheme {
        case "http", "https", "ftp", "sftp", "ssh": return url.host != nil
        case "mailto", "tel", "facetime", "slack", "x-apple.systempreferences": return true
        default: return false
        }
    }

    private static func readImage(from pasteboard: NSPasteboard) -> (png: Data, thumbnail: Data?, size: CGSize)? {
        let png: Data
        if let data = pasteboard.data(forType: .png) {
            png = data
        } else if let tiff = pasteboard.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: tiff),
                  let data = rep.representation(using: .png, properties: [:]) {
            png = data
        } else {
            return nil
        }
        guard png.count <= maxImageBytes, let rep = NSBitmapImageRep(data: png) else { return nil }
        let size = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        return (png, ImageTools.thumbnail(from: rep, maxPixel: 320), size)
    }

    static func hash(_ kind: String, _ content: String) -> String {
        hash(data: Data((kind + "\u{0}" + content).utf8))
    }

    static func hash(data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}

